export const MESSAGES: Record<Lang, Messages> = { es, pt };

// The app-wide language, for code outside React (lib helpers that return
// labels). LangProvider sets it before rendering and remounts the tree when it
// changes, so every label is read again. Spanish until then (and in tests).
let current: Lang = 'es';

export function currentLang(): Lang {
  return current;
}

export function setCurrentLang(lang: Lang) {
  current = lang;
}

// The messages of the current language.
export function tr(): Messages {
  return MESSAGES[current];
}

// The date-fns locale and the Intl locale of the current language.
export function dateLocale() {
  return current === 'pt' ? ptBR : dfEs;
}

export function intlLocale(): string {
  return current === 'pt' ? 'pt-BR' : 'es';
}

// Demo customers are labelled "Name · Country".
export function langFromCustomerLabel(label: string | null | undefined): Lang | null {
  const country = label?.split('·')[1]?.trim().toLowerCase();
  if (!country) return null;
  return country === 'brasil' || country === 'brazil' ? 'pt' : 'es';
}

// Without a saved choice: the demo customer's country, else the browser,
// else Spanish.
export function defaultLang({
  customerLabel,
  navigatorLanguage,
}: {
  customerLabel?: string | null;
  navigatorLanguage?: string | null;
}): Lang {
  const byCustomer = langFromCustomerLabel(customerLabel);
  if (byCustomer) return byCustomer;
  return navigatorLanguage?.toLowerCase().startsWith('pt') ? 'pt' : 'es';
}
